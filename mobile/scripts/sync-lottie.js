// Registers the Lottie animations in assets/lottie so cook mode can play them.
// Name files after the step action they show (see assets/lottie/README.md), e.g. mix.json, bake.json.
// Extra versions of the same action (e.g. mix-2.json, mix-3.json) take turns from step to step.
// Run after adding or removing files:  npm run sync-lottie
const fs = require('fs');
const path = require('path');

const ACTIONS = ['mix', 'knead', 'rise', 'bake', 'boil', 'chop', 'fry', 'whisk', 'pour', 'season', 'cool', 'serve', 'hello'];
const dir = path.join(__dirname, '..', 'assets', 'lottie');
const out = path.join(__dirname, '..', 'src', 'components', 'art', 'lottie-files.ts');

const files = fs.existsSync(dir) ? fs.readdirSync(dir).filter(f => /\.(json|lottie)$/i.test(f)).sort() : [];
const byAction = {};
for (const f of files) {
  const action = f.replace(/\.(json|lottie)$/i, '').replace(/-\d+$/, '').toLowerCase();
  if (!ACTIONS.includes(action)) { console.warn(`skipped ${f} (unknown action; use one of: ${ACTIONS.join(', ')})`); continue; }
  (byAction[action] ||= []).push(f);
}

const lines = Object.entries(byAction).map(([a, list]) => `  ${a}: [${list.map(f => `require('../../../assets/lottie/${f}')`).join(', ')}],`);
fs.writeFileSync(out, `// AUTO-GENERATED by scripts/sync-lottie.js from assets/lottie. Don't edit; run: npm run sync-lottie
export const LOTTIE: Record<string, unknown[]> = {
${lines.join('\n')}
};
`);
console.log(`lottie: ${files.length} file(s) for ${Object.keys(byAction).length} action(s)`);
